#!/usr/bin/env bash
# Purpose: Process local .sra files to generate gzipped fastq; rename dump outputs to match expected naming;
#   detect running dump processes to avoid duplicate starts
# Input: none (reads .sra from local cache; detects existing dump child processes)
# Output: data/fq2/<acc>/ (gzipped fastq files with corrected naming)
# 02b: Modified version of 02_quant.sh. All runs use route B (generate gz from local .sra).
#
# Modifications from 02:
#   - Since fastq-dump creates output names from the input file name, from `SRR32119705.final.sra`
#     `SRR32119705.final_1.fastq.gz` is produced. It conflicts with `SRR32119705_1.fastq.gz`
#     expected by count_run and fails. -> Rename after dump.
#   - Detect an already-running dump (a child process that survives even after the parent script is killed),
#     and wait for completion without starting a duplicate. The corruption in 01c was caused by concurrent writes to the same path, so
#     here we strictly enforce "one file, one writer".
#
# Output is isolated to data/fq2/<acc>/ (the old curl that cannot be stopped keeps writing to data/fastq).
set -uo pipefail
W="${APSC_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." && pwd)}"
R=$W/ref; FQ=$W/data/fq2; SRA=$W/data/sra; CNT=$W/data/counts; L=$W/logs/02b_quant.log
export HOME=$W/.home; mkdir -p "$HOME" "$CNT" "$FQ"
export KALLISTO_BIN="$(command -v kallisto)"
export BUSTOOLS_BIN="$(command -v bustools)"
PY=${APSC_PYTHON:-python}
say(){ echo "[$(date -u +%FT%TZ)] $*" >> $L; }
free_g(){ df -k "$W" | tail -1 | awk '{print int($4/1048576)}'; }
progress(){ date -u +%FT%TZ > $W/logs/quant_progress.txt; }
sz(){ stat -f%z "$1" 2>/dev/null || echo 0; }

# ---- Wait for an in-progress dump: consider it complete if both files' sizes do not change for 10 minutes ----
wait_stable(){ # $1=dir $2=glob_prefix
  local d=$1 pre=$2 a b n=0
  while :; do
    a=$(cat <(sz "$d/${pre}_1.fastq.gz") <(sz "$d/${pre}_2.fastq.gz") | paste -sd+ - | bc)
    sleep 300; progress
    b=$(cat <(sz "$d/${pre}_1.fastq.gz") <(sz "$d/${pre}_2.fastq.gz") | paste -sd+ - | bc)
    if [ "$a" = "$b" ]; then
      n=$((n+1)); [ $n -ge 2 ] && { say "  $pre: 10分変化なし -> dump 完了とみなす（計 $((b/1000000000))G）"; return 0; }
    else
      n=0; say "  $pre: dump 継続中 $((b/1000000000))G (+$(( (b-a)/1000000 ))MB/5分)"
    fi
  done
}

dump_run(){ # $1=acc
  local acc=$1 d=$FQ/$acc base=${acc}.final
  mkdir -p "$d"
  if [ -s "$d/${acc}_1.fastq.gz" ] && [ -s "$d/${acc}_2.fastq.gz" ]; then say "$acc: gz 既存 — skip"; return 0; fi
  if [ "$(sz "$d/${base}_1.fastq.gz")" -gt 0 ] || [ "$(sz "$d/${base}_2.fastq.gz")" -gt 0 ]; then
    say "$acc: 既存の dump を検出（別プロセス）— 二重起動せず完了を待つ"
  else
    say "$acc: fastq-dump --split-files --gzip 開始（空き $(free_g)G）"
    nohup fastq-dump --split-files --gzip -O "$d" "$SRA/$acc.final.sra" >> $L 2>&1 &
    sleep 30
  fi
  wait_stable "$d" "$base"
  [ -s "$d/${base}_1.fastq.gz" ] && [ -s "$d/${base}_2.fastq.gz" ] || { say "$acc: dump 出力なし"; return 1; }
  mv "$d/${base}_1.fastq.gz" "$d/${acc}_1.fastq.gz"
  mv "$d/${base}_2.fastq.gz" "$d/${acc}_2.fastq.gz"
  say "$acc: リネーム完了 R1 $(sz "$d/${acc}_1.fastq.gz") / R2 $(sz "$d/${acc}_2.fastq.gz")"
  progress
}

count_run(){ # $1=acc $2=lab
  local acc=$1 lab=$2 d=$FQ/$acc out=$CNT/$2
  local r1=$d/${acc}_1.fastq.gz r2=$d/${acc}_2.fastq.gz
  [ -s "$out/verify.json" ] && { say "$lab: 定量済み — skip"; return 0; }
  [ -s "$r1" ] && [ -s "$r2" ] || { say "$lab: FASTQ が揃っていない"; return 1; }
  say "$lab: kb count start（空き $(free_g)G）"
  mkdir -p "$out"
  kb count --kallisto "$KALLISTO_BIN" --bustools "$BUSTOOLS_BIN" \
     -i $R/index.idx -g $R/t2g.txt -x 10xv3 -o "$out" -t 6 -m 24G --overwrite "$r1" "$r2" \
     > $W/logs/kb_$lab.log 2>&1
  progress
  [ -s "$out/counts_unfiltered/cells_x_genes.mtx" ] || { say "$lab: kb count 失敗（logs/kb_$lab.log）"; return 1; }
  $PY - "$out" "$lab" <<'PY' >> $L 2>&1
import sys, json, os
out, lab = sys.argv[1], sys.argv[2]
p = os.path.join(out, "counts_unfiltered", "cells_x_genes.mtx")
with open(p) as f:
    f.readline(); f.readline(); nb, ng, nnz = map(int, f.readline().split())
    tot = sum(int(float(l.rsplit(" ", 1)[1])) for l in f)
rec = dict(label=lab, barcodes=nb, genes=ng, nonzero=nnz, total_umi=tot)
ri = os.path.join(out, "run_info.json")
if os.path.exists(ri):
    d = json.load(open(ri)); rec.update({k: d.get(k) for k in ("n_processed","n_pseudoaligned","p_pseudoaligned","n_targets")})
json.dump(rec, open(os.path.join(out, "verify.json"), "w"), indent=1)
print("VERIFY", json.dumps(rec))
PY
  say "$lab: COUNT OK $(tr -d '\n ' < $out/verify.json | cut -c1-220)"
  rm -rf "$d"                     # Release intermediate FASTQ files from this run (generated by this pipeline)
  say "$lab: FASTQ 解放、空き $(free_g)G"
  progress
}

say "=== 02b start 空き $(free_g)G ==="
progress
# For run→donor mapping, treat ref/run_donor_map_v2.csv as the sole source of truth (to prevent recurrence of CAP1/CAP3 mix-up)
while IFS=, read -r acc lab _rest; do
  [ "$acc" = "run_accession" ] && continue
  [ -z "$acc" ] && continue
  [ -s "$CNT/$lab/verify.json" ] && { say "$lab: 完了済み — skip"; continue; }
  dump_run "$acc" || { say "$lab: dump 失敗 — 次へ"; continue; }
  count_run "$acc" "$lab" || say "$lab: 定量失敗 — 次へ"
done < $R/run_donor_map_v2.csv
say "=== 02b DONE counted=$(ls $CNT/*/verify.json 2>/dev/null | wc -l | tr -d ' ')/3 空き $(free_g)G ==="
progress
